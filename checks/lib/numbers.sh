#!/usr/bin/env bash
# Числа из текста лога. Подключается проверками, которые сравнивают записанные
# в лог величины с пределами.
#
# first_number <текст> — первое число записи, запятая становится точкой, пробелы
# между разрядами убираются; пусто, если числа нет
first_number() {
	echo "$1" | tr ',' '.' | sed -E 's/([0-9])[[:space:]]+([0-9])/\1\2/g' | grep -Eo '[0-9]+(\.[0-9]+)?' | head -1
}

# within <число> <от> <до> — число в пределах, включая края
within() {
	[ -n "$1" ] && awk -v x="$1" -v lo="$2" -v hi="$3" 'BEGIN { exit !(x >= lo && x <= hi) }'
}
