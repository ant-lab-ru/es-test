#!/usr/bin/env bash
# Лог прогона на устройстве. Подключается проверками заданий, где студент запускает
# у себя Python-скрипт: тот опрашивает плату по USB и записывает обмен в файл,
# который уезжает в репозиторий вместе с кодом.
#
# Проверка на серверах GitHub платы не видит. Она читает этот файл и убеждается,
# что прошивка отвечала так, как требует задание, а на другом конце провода была
# именно Raspberry Pi Pico: в шапке лога стоят её код USB-устройства и серийный номер.
#
# device_log <путь к логу> <номер задания> — читает шапку лога и заводит переменные
# DEVICE_LOG (путь к нормализованной копии) и DEVICE_SERIAL (серийный номер платы).
# Возвращает ненулевой код, если лога нет: тогда пункты по его содержимому пропускаются.

DEVICE_USB="2e8a:000a"
DEVICE_LOG=""
DEVICE_SERIAL=""

device_log() {
	local path="$1"
	local task="$2"
	local log

	DEVICE_LOG=""
	DEVICE_SERIAL=""

	if [ ! -f "$path" ]; then
		fail "Нет лога прогона на устройстве: $(basename "$path")"
		note "Лог пишет Python-скрипт задания: запустите его на компьютере с подключённой платой."
		return 1
	fi

	log="$(normalize "$path")"

	if grep -Eq "^задание: $task[[:space:]]*$" "$log"; then
		ok "Лог снят по заданию $task"
	else
		fail "В шапке лога не задание $task"
		note "Скрипт пишет номер задания сам — похоже, лог снят другим скриптом."
	fi

	if grep -Eq "^устройство: $DEVICE_USB[[:space:]]*$" "$log"; then
		ok "Лог снят с платы Raspberry Pi Pico"
	else
		fail "В шапке лога не код USB-устройства Raspberry Pi Pico ($DEVICE_USB)"
		note "Скрипт ищет плату по коду производителя и устройства: другой код — другая плата."
	fi

	DEVICE_SERIAL="$(grep -E '^серийный номер: ' "$log" | head -1 | sed 's/^серийный номер: //; s/[[:space:]]*$//')"
	if echo "$DEVICE_SERIAL" | grep -Eq '^[0-9A-Fa-f]{8,}$'; then
		ok "В логе записан серийный номер платы: $DEVICE_SERIAL"
	else
		fail "В логе нет серийного номера платы"
		note "Серийный номер приходит от самой платы и говорит, что скрипт работал с железом."
	fi

	DEVICE_LOG="$log"
	return 0
}

# device_received <нормализованный лог> — строки, принятые от платы, без меток времени.
device_received() {
	sed -n 's/^[[:space:]]*[0-9.]\{1,\}[[:space:]]*<-- //p' "$1"
}

# device_sent <нормализованный лог> — строки, отправленные плате.
device_sent() {
	sed -n 's/^[[:space:]]*[0-9.]\{1,\}[[:space:]]*--> //p' "$1"
}
