#!/usr/bin/env bash
# Обмен с платой по шагам. Подключается проверками, которым важно не только что
# ответила плата, но и на какую команду и когда: время ответа, порядок ответов,
# повтор одной команды несколько раз за прогон.
#
# exchange_table <нормализованный лог> — строка на каждую строку, принятую от платы,
# поля через табуляцию: номер шага, команда шага, время отправки, время ответа, текст.
# Номер шага растёт с каждой отправленной командой. Строки до первой команды пропускаются.

exchange_table() {
	awk '
		/-->/ { step++; command = $3; sent = $1; next }
		/<--/ {
			if (step == 0) next
			text = substr($0, index($0, "<-- ") + 4)
			printf "%d\t%s\t%s\t%s\t%s\n", step, command, sent, $1, text
		}
	' "$1"
}

# exchange_replies <таблица> <команда> <номер вызова> — ответы на N-й вызов команды
# (нумерация с 1), по строке на ответ: время ответа, текст.
exchange_replies() {
	echo "$1" | awk -F '\t' -v command="$2" -v nth="$3" '
		$2 == command && $1 != last { last = $1; seen++ }
		$2 == command && seen == nth && $1 == last { print $4 "\t" $5 }
	'
}

# exchange_sent_at <нормализованный лог> <команда> <номер вызова> — время N-й отправки команды.
exchange_sent_at() {
	awk -v command="$2" -v nth="$3" '/-->/ && $3 == command { seen++; if (seen == nth) { print $1; exit } }' "$1"
}

# exchange_calls <нормализованный лог> <команда> — сколько раз команда отправлена.
exchange_calls() {
	awk -v command="$2" '/-->/ && $3 == command { n++ } END { print n + 0 }' "$1"
}
